export const DECOR_BY_ID: Record<string, DecorDef> = byId(DECOR);

export function getDecorDef(id: string): DecorDef | undefined {
  return DECOR_BY_ID[id];
}

/** Plants/epiphytes/corals that can sit on top of hardscape (placement lifts them onto rock/wood). */
export const EPIPHYTE_VISUALS = new Set([
  'plant_java_fern',
  'plant_anubias',
  'plant_moss',
  'coral_zoanthid',
  'coral_mushroom',
  'coral_gsp',
  'coral_leather',
  'coral_hammer',
  'coral_torch',
  'coral_frogspawn',
  'coral_acropora',
  'coral_gorgonian',
  'anemone_bta',
  'macro_gracilaria',
  'macro_chaeto',
]);

/** Items that float at the water surface (y is set from the water line, not the substrate). */
export const FLOATING_VISUALS = new Set(['plant_floating']);
/** lane:brackish — emergent plants: rooted in the bed, their crown may reach just above the water line. */
export const EMERGENT_VISUALS = new Set(['plant_mangrove']);

export const isEpiphyte = (def: DecorDef) => EPIPHYTE_VISUALS.has(def.visual);
export const isFloating = (def: DecorDef) => FLOATING_VISUALS.has(def.visual);
export const isEmergent = (def: DecorDef) => EMERGENT_VISUALS.has(def.visual); // lane:brackish
export const isLiving = (def: DecorDef) => def.category === 'plant' || def.category === 'coral' || def.category === 'anemone';
