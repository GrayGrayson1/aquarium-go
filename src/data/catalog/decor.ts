/**
 * Decor catalog (hardscape, plants, corals, anemones, ornaments, enrichment).
 * OWNER: lane "aquascape".
 *
 * Conventions
 * - `size` is the item's bounding box in metres at scale 1 (w along x, d along z, h up from the base).
 *   The procedural generators in src/render/decor/gen/** keep every visual inside this box, and the AI
 *   uses `decorCollider` / `decorAnchors` (src/sim/tankSpace.ts) built from the same numbers.
 * - Anchor offsets are decor-local (before rotation/scale), y up from the base. The generators build real
 *   geometry at every anchor (a cave mouth, a hitching branch, a flat leaf, a host disc...).
 * - `habitat` numbers are per item at scale 1. `cover` and `sightBreak` are "per 10 gallons"
 *   (the sim normalises them by tank volume). `nitrateUptake` is ppm/hour-ish at full growth in a 10 gal.
 * - `visual` keys are interpreted by src/render/decor/gen/index.ts.
 */
