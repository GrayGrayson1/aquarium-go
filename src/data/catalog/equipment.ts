/**
 * Equipment catalog. OWNER: lane "waterlab".
 *
 * How the water sim (src/sim/water) reads `stats`:
 * - filter      flowGph = rated turnover; bioCapacity = animal-waste units/hour the media can nitrify at full maturity
 *               (1 unit = the hourly waste of a bioload-1 animal, ≈ a 5 cm community fish); mechanical = 0..1 detritus
 *               capture; aeration/agitation = gas exchange. `setting` (0.3..1) throttles flow on adjustable filters.
 * - heater      power = watts. `setting` = thermostat °C. Heating rate ≈ W × 0.86 / litres  °C per hour.
 * - chiller     power = watts of heat removed. `setting` = target °C.
 * - fan         power = °C of evaporative cooling below room temperature (it also doubles evaporation).
 * - light       par 0..1 (photosynthetic intensity) and spectrum. `setting` = intensity multiplier.
 * - powerhead / wavemaker  flowGph; `setting` 0..1 = flow fraction (seahorses need it low).
 * - skimmer / refugium / uv  export 0..1 = nutrient export / algae & bacteria-bloom control.
 * - airstone    aeration/agitation only.
 * - ato         keeps the level topped with fresh water (salinity stays stable).
 * - autofeeder  `setting` = dry-food feedings per day. It dispenses DRY food only (isAutofeederFood in foods.ts) — one
 *               food per feeding, the one in stock that the most animals in the tank eat (src/sim/care/autofeed.ts).
 * - co2         `setting` 0..1 = injection rate (planted growth up, pH down).
 * - lid         cuts evaporation and stops jumpers escaping.
 * `upkeep` is the daily running cost at 100 % duty — thermal devices are charged by estimated duty cycle.
 * `failureRate` is the per-game-day failure chance of a new unit; wear multiplies it (see water sim).
 */
